export type TableRibbonLabels = Record<keyof typeof ROWS, string>

const ORDER: readonly Lang[] = [
  'en',
  'zh',
  'zh-TW',
  'ja',
  'ko',
  'fr',
  'de',
  'es',
  'th',
  'id',
  'ru',
  'ar',
  'pt',
  'it',
  'pl',
  'cs',
  'nl',
  'ms',
  'he',
  'hi',
] as const

const CACHE = new Map<Lang, TableRibbonLabels>()

export function tableRibbonLabels(lang: Lang): TableRibbonLabels {
  let labels = CACHE.get(lang)
  if (!labels) {
    const col = Math.max(0, ORDER.indexOf(lang))
    const out: Record<string, string> = {}
    for (const [key, cells] of Object.entries(ROWS)) out[key] = cells[col] ?? cells[0] ?? key
    labels = out as TableRibbonLabels
    CACHE.set(lang, labels)
  }
  return labels
}

/** "Medium Style 2 - Accent 1" in the UI language (the gallery's tooltip text). */
export function localizedTableStyleName(
  l: TableRibbonLabels,
  style: { name: string; family: string; accent?: string },
): string {
  const fam: Record<string, string> = {
    light: l.famLight,
    medium: l.famMedium,
    dark: l.famDark,
  }
  if (/^No Style, No Grid$/.test(style.name)) return l.noStyleNoGrid
  if (/^No Style, Table Grid$/.test(style.name)) return l.noStyleGrid
  const m = /^(Light|Medium|Dark) Style (\d)(?: - Accent (\d)(?:\/Accent (\d))?)?$/.exec(style.name)
  if (!m) return style.name
  const base = `${fam[m[1]!.toLowerCase()]} ${m[2]}`
  if (!m[3]) return base
  const tail = m[4] ? `${l.accent} ${m[3]}/${l.accent} ${m[4]}` : `${l.accent} ${m[3]}`
  return `${base} - ${tail}`
}
