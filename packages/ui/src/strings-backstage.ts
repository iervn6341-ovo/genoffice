export type BackstageLabels = Record<keyof typeof ROWS, string>

const ORDER: readonly Lang[] = [
  'en',
  'zh',
  'zh-TW',
  'ja',
  'ko',
  'fr',
  'de',
  'es',
  'th',
  'id',
  'ru',
  'ar',
  'pt',
  'it',
  'pl',
  'cs',
  'nl',
  'ms',
  'he',
  'hi',
] as const

function labelsFor(lang: Lang): BackstageLabels {
  const col = Math.max(0, ORDER.indexOf(lang))
  const out: Record<string, string> = {}
  for (const [key, cells] of Object.entries(ROWS)) out[key] = cells[col] ?? cells[0] ?? key
  return out as BackstageLabels
}

const CACHE = new Map<Lang, BackstageLabels>()

export function backstageLabels(lang: Lang): BackstageLabels {
  let labels = CACHE.get(lang)
  if (!labels) {
    labels = labelsFor(lang)
    CACHE.set(lang, labels)
  }
  return labels
}
