export type PrintJobStrings = { -readonly [K in keyof typeof base]: string }

export function printJobStringsFor(lang: string): PrintJobStrings {
  const key = lang === 'zh-TW' ? 'zh-TW' : lang
  return { ...base, ...(localized[key as keyof typeof localized] ?? {}) }
}
