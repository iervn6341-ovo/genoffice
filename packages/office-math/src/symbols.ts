export function symbolCodePoint(char: string): string {
  return (char.codePointAt(0) ?? 0).toString(16).toUpperCase().padStart(4, '0')
}
export function findSymbolByCodePoint(value: string): string | null {
  const hex = value.trim().replace(/^(U\+|0x)/i, '')
  if (!/^[0-9a-f]{1,6}$/i.test(hex)) return null
  const code = Number.parseInt(hex, 16)
  if (
    code < 0x20 ||
    code > 0x10ffff ||
    (code >= 0xd800 && code <= 0xdfff) ||
    code === 0xfffe ||
    code === 0xffff
  )
    return null
  return String.fromCodePoint(code)
}
export function symbolSearchText(char: string): string {
  return `${char} ${SYMBOL_NAMES[char] ?? ''} U+${symbolCodePoint(char)}`
}
